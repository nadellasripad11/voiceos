'use strict';
/**
 * Brings the website's scene (the singularity in the middle) into the desktop
 * console, so the two look the same.
 *
 *   node scripts/build-console-orbit.js
 *
 * The website's files are ES modules; the console loads plain scripts from
 * file://, where module imports are refused. So each module is wrapped in its
 * own function scope (two of them declare `clamp` and `TAU`), its exports are
 * handed to the next, and the whole thing sets window.createSingularity.
 * Rerun it after changing any of web/singularity.js, core-field.js,
 * scene-layout.js or fluid-simulation.js.
 */
const fs = require('fs');
const path = require('path');

const WEB = path.join(__dirname, '..', 'web');
const OUT = path.join(__dirname, '..', 'src', 'renderer', 'console');
// In dependency order: each one's exports are in scope for the ones after it.
const MODULES = ['fluid-simulation.js', 'core-field.js', 'scene-layout.js', 'singularity.js'];

/** A change the console relies on; if the site's code moved, say so rather than ship without it. */
function must(src, file, from, to) {
  if (!src.includes(from)) throw new Error(`${file}: could not find ${JSON.stringify(from.slice(0, 50))}; update this script`);
  return src.replace(from, to);
}

const parts = MODULES.map((file) => {
  // Checkouts on Windows may have CRLF; the patterns below are written with LF.
  let src = fs.readFileSync(path.join(WEB, file), 'utf8').replace(/\r\n/g, '\n');
  const names = [...src.matchAll(/^export (?:function|const|let|class) (\w+)/gm)].map((m) => m[1]);
  src = src
    .replace(/^import .*$/gm, '')
    .replace(/^export /gm, '')
    // The picture sits next to the console's other art.
    .replace(/new URL\((['"])\.\/assets\/([\w.-]+)\1\s*,\s*import\.meta\.url\)\.href/g, "'art/$2'");
  if (file === 'singularity.js') {
    // A still scene need not redraw: the console turns the idle refresh off
    // (ORBIT_IDLE_MS = 0; redrawing the unchanged picture cost ~20% of a core)
    // and wakes the scene itself when something changes.
    src = must(src, file, 'else refreshTimer=setTimeout(()=>{refreshTimer=0;requestFrame();},180);',
      'else if(window.ORBIT_IDLE_MS!==0)refreshTimer=setTimeout(()=>{refreshTimer=0;requestFrame();},window.ORBIT_IDLE_MS||180);');
    src = must(src, file, '  return {\n    cue(type) {', '  return {\n    wake: invalidate,\n    cue(type) {');
  }
  if (/import\.meta|\bimport\(/.test(src)) throw new Error(`${file} still imports something this script does not handle`);
  return `// --- ${file} ---\nconst { ${names.join(', ')} } = (() => {\n${src}\nreturn { ${names.join(', ')} };\n})();`;
});

const out = `'use strict';
// GENERATED by scripts/build-console-orbit.js from the website's scene (web/).
// Do not edit here: change web/ and run the script again.
(function () {
${parts.join('\n\n')}

window.createSingularity = createSingularity;
})();
`;
fs.writeFileSync(path.join(OUT, 'orbit.js'), out);
fs.copyFileSync(path.join(WEB, 'assets', 'orbital-sphere.png'), path.join(OUT, 'art', 'orbital-sphere.png'));
console.log(`wrote ${path.relative(process.cwd(), path.join(OUT, 'orbit.js'))} (${(out.length / 1024).toFixed(0)} KB)`);
